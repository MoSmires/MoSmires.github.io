"""**Fonction qui permet de générer les résultats sous format MOT après avoir combiné les deux briques YOLO et DeepSort**"""

def genererMOT(model, Chemin, Dossierbaseline_out, sequences, Seuil_Confiance, Afficher_vid, Resize, Log):
    if os.path.exists(Dossierbaseline_out):
        print(f"[INFO] Suppression de l'ancien dossier : {Dossierbaseline_out}")
        shutil.rmtree(Dossierbaseline_out)

    os.makedirs(Dossierbaseline_out, exist_ok=True)
    try:
        for seq in sequences:
            print(f"\n--- Traitement de la séquence : {seq} ---")

            seq_path = os.path.join(Chemin, seq, "images")
            save_dir = os.path.join(Dossierbaseline_out, seq)
            os.makedirs(save_dir, exist_ok=True)

            # Utilisation de 'with' pour garantir la fermeture des fichiers
            det_path = os.path.join(save_dir, "det.txt")
            track_path = os.path.join(save_dir, f"{seq}.txt")

            with open(det_path, "w") as det_file, open(track_path, "w") as track_file:

                tracker = DeepSort(max_age=30, n_init=3, nms_max_overlap=1.0, max_cosine_distance=0.2)
                image_files = sorted([f for f in os.listdir(seq_path) if f.lower().endswith(('.jpg', '.png'))])
                total_frames = len(image_files)

                if total_frames == 0:
                    print(f"[WARN] Aucune image trouvée dans {seq_path}, skip.")
                    continue

                frame_idx = 1
                t_start = time.time()

                for img_name in image_files:
                    img_path = os.path.join(seq_path, img_name)
                    frame = cv2.imread(img_path)
                    if frame is None:
                        frame_idx += 1
                        continue

                    if Log == 0:
                        print(f"Sequence {seq} — frame {frame_idx}/{total_frames}", end='\r', flush=True)
                    elif frame_idx % Log == 0 or frame_idx == 1 or frame_idx == total_frames:
                        print(f"Sequence {seq} — frame {frame_idx}/{total_frames}")

                    results = model(frame, verbose=False)
                    yolo_dets = []

                    for r in results:
                        for box in r.boxes:
                            cls_id = int(box.cls.cpu().numpy()[0])
                            if cls_id != 0: continue

                            x1, y1, x2, y2 = box.xyxy.cpu().numpy()[0]
                            conf = float(box.conf.cpu().numpy()[0])

                            if conf >= Seuil_Confiance:
                                w, h = x2 - x1, y2 - y1
                                yolo_dets.append([[x1, y1, w, h], conf, "person"])
                                det_file.write(f"{frame_idx},-1,{x1:.2f},{y1:.2f},{w:.2f},{h:.2f},{conf:.3f},-1,-1,-1\n")

                    tracks = tracker.update_tracks(yolo_dets, frame=frame)

                    for track in tracks:
                        if not track.is_confirmed(): continue

                        tid = track.track_id
                        l, t, rgt, b = track.to_ltrb()
                        tw, th = rgt - l, b - t
                        track_file.write(f"{frame_idx},{tid},{l:.2f},{t:.2f},{tw:.2f},{th:.2f},1,-1,-1,-1\n")

                        if Afficher_vid:
                            cv2.rectangle(frame, (int(l), int(t)), (int(rgt), int(b)), (0, 255, 0), 2)
                            cv2.putText(frame, f"ID:{tid}", (int(l), int(t)-5), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0,255,0), 2)

                    if Afficher_vid:
                        display_frame = cv2.resize(frame, Resize) if Resize else frame
                        cv2.imshow("MOT20 Multi-Sequence Tracker", display_frame)
                        if cv2.waitKey(1) & 0xFF == ord('q'):
                            break

                    frame_idx += 1

                duration = time.time() - t_start
                fps = (frame_idx - 1) / duration if duration > 0 else 0.0
                print(f"\nSéquence {seq} terminée : {frame_idx - 1} trames ({fps:.2f} FPS)")

    except KeyboardInterrupt:
        print("\n[INFO] Interruption clavier détectée.")

    finally:

        if Afficher_vid:
            try:
                cv2.destroyAllWindows()
            except:
                pass
        print("[INFO] Traitement terminé.")

"""**Execution de générer MOT sur les données d'entraînement**"""

