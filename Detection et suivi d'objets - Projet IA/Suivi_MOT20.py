"""**Mise en forme des labels à partir de "gt.txt" pour le Fine Tuning** : Yolo a besoin d'un fichier par image."gt.txt" doit alors être parsé pour construire un fichiers de labels pour pouvoir effectuer l'entraînement"""

def get_sequence_info(seq_path):
    """Lit le fichier seqinfo.ini pour obtenir la résolution et le dossier des images."""
    ini_path = os.path.join(seq_path, 'seqinfo.ini')
    if not os.path.exists(ini_path):
        raise FileNotFoundError(f"seqinfo.ini manquant dans {seq_path}")

    config = configparser.ConfigParser()
    config.read(ini_path)

    w = int(config.get('Sequence', 'imWidth'))
    h = int(config.get('Sequence', 'imHeight'))
    img_dir = config.get('Sequence', 'imDir')
    return w, h, img_dir

def process_mot_in_place(mot_root):
    """
    Convertit les labels MOT en YOLO et réorganise les dossiers
    pour la compatibilité Ultralytics.
    """
    # 1. Lister les séquences (MOT20-01, MOT20-02, etc.)
    sequences = [d for d in os.listdir(mot_root) if os.path.isdir(os.path.join(mot_root, d))]

    for seq in sequences:
        seq_path = os.path.join(mot_root, seq)
        print(f"--- Traitement de {seq} ---")

        # 2. Renommer 'img1' en 'images' (CRUCIAL pour YOLO)
        old_img_path = os.path.join(seq_path, 'img1')
        new_img_path = os.path.join(seq_path, 'images')

        if os.path.exists(old_img_path):
            # Supprimer le dossier 'images' s'il existe déjà pour éviter les erreurs de renommage
            if os.path.exists(new_img_path):
                shutil.rmtree(new_img_path)
            os.rename(old_img_path, new_img_path)
            print(f"Renommé : img1 -> images")

        # Récupérer les infos de résolution
        try:
            w, h, _ = get_sequence_info(seq_path)
        except Exception as e:
            print(f"Erreur seqinfo pour {seq}: {e}")
            continue

        # Préparer le dossier labels (au même niveau que 'images')
        labels_out = os.path.join(seq_path, 'labels')
        if os.path.exists(labels_out):
            shutil.rmtree(labels_out)
        os.makedirs(labels_out, exist_ok=True)

        gt_file = os.path.join(seq_path, 'gt', 'gt.txt')
        if not os.path.exists(gt_file):
            print(f"Pas de fichier gt.txt trouvé pour {seq}")
            continue

        # Conversion du fichier gt.txt
        count = 0
        with open(gt_file, 'r') as f:
            for line in f:
                parts = line.strip().split(',')
                if len(parts) < 7: continue

                # Filtrer Pedestrian (Classe 1 dans MOT20)
                if parts[7] != '1': continue

                frame_id = int(parts[0])
                xmin, ymin, width, height = float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5])

                # Calcul YOLO (Normalisé 0-1)
                x_center = (xmin + width / 2.0) / w
                y_center = (ymin + height / 2.0) / h
                w_norm = width / w
                h_norm = height / h

                label_filename = f"{frame_id:06d}.txt"
                label_path = os.path.join(labels_out, label_filename)

                with open(label_path, 'a') as lf:
                    lf.write(f"0 {x_center:.6f} {y_center:.6f} {w_norm:.6f} {h_norm:.6f}\n")
                count += 1

        #  Supprimer les anciens fichiers cache pour forcer un nouveau scan
        cache_file = os.path.join(seq_path, "images.cache")
        if os.path.exists(cache_file):
            os.remove(cache_file)

        print(f"Terminé : {count} annotations créées.")

# EXECUTION
