"""**Fonction qui évalue les performances : mota', 'idf1', 'motp', 'num_switches', 'precision', 'recall'**"""

#---------------------------Performances----------------------------------------------#
def evaluate_mot_results(Chemin,Dossierbaseline_out,sequences):
    accs = []
    names = []

    # Vérification de l'existence du dossier de résultats
    if not os.path.exists(Dossierbaseline_out):
        print(f"Le dossier {Dossierbaseline_out} n'existe pas.")
        return

    sequences = [d for d in os.listdir(Dossierbaseline_out) if os.path.isdir(os.path.join(Dossierbaseline_out, d))]

    for seq in sequences:
        print(f"--- Analyse en cours : {seq} ---")

        gt_file = os.path.join(Chemin, seq, "gt", "gt.txt")
        res_file = os.path.join(Dossierbaseline_out, seq, f"{seq}.txt")

        if not os.path.exists(gt_file) or not os.path.exists(res_file):
            print(f"Fichiers manquants pour {seq}. Vérifiez gt.txt et votre sortie .txt")
            continue

        # Chargement des données
        gt_data = mm.io.loadtxt(gt_file, fmt="mot16")
        res_data = mm.io.loadtxt(res_file, fmt="mot16")

        acc = mm.MOTAccumulator(auto_id=True)

        # Extraction des indices de trames (frames)
        # On utilise .index.get_level_values(0) car motmetrics utilise un MultiIndex (Frame, ID)
        all_frames = gt_data.index.get_level_values(0).unique()

        for frame in all_frames:
            # Données de vérité terrain (GT)
            gt_frame = gt_data.loc[frame]
            gt_ids = gt_frame.index.values
            gt_boxes = gt_frame.iloc[:, 0:4].values

            # Données de vos prédictions (RES)
            if frame in res_data.index.get_level_values(0):
                res_frame = res_data.loc[frame]
                res_ids = res_frame.index.values
                res_boxes = res_frame.iloc[:, 0:4].values
            else:
                # Si aucune détection pour cette trame
                res_ids = []
                res_boxes = np.empty((0, 4))

            # Calcul de la distance IoU
            distances = mm.distances.iou_matrix(gt_boxes, res_boxes, max_iou=0.5)

            # Mise à jour de l'accumulateur (C'est ici que le MOTA se construit)
            acc.update(gt_ids, res_ids, distances)

        accs.append(acc)
        names.append(seq)

    # Synthèse des résultats
    mh = mm.metrics.create()
    summary = mh.compute_many(
        accs,
        metrics=['mota', 'idf1', 'motp', 'num_switches', 'precision', 'recall'],
        names=names,
        generate_overall=True
    )

    print("\n" + "="*80)
    print(" RÉSULTATS DE L'ÉVALUATION MOTA")
    print("="*80)

    print(mm.io.render_summary(summary, formatters=mh.formatters, namemap=mm.io.motchallenge_metric_names))

"""**Execution de l'évaluation de performance sur les données d'entraînement**"""

